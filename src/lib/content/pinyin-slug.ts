function normalizeToken(value: string) {
  return value
    .split('')
    .map((char) => toneMarks[char] ?? char.normalize('NFKD').replace(/[̀-ͯ]/g, ''))
    .join('')
}

export function transliterateToSlugInput(input: string) {
  return input
    .trim()
    .split('')
    .map((char) => {
      if (/^[a-zA-Z0-9\s_-]$/.test(char)) {
        return char
      }

      const mapped = pinyinByChar.get(char)
      if (mapped) {
        return ` ${mapped} `
      }

      return ' '
    })
    .join('')
}

export function createSlugFromTitle(title: string) {
  return slugify(normalizeToken(transliterateToSlugInput(title)))
}

